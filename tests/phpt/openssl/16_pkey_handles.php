function check_forged_handle($handle) {
    var_dump(openssl_pkey_get_public($handle) === false);
    var_dump(openssl_pkey_get_private($handle) === false);

    $result = '';
    var_dump(openssl_public_encrypt('data', $result, $handle));
    var_dump(openssl_private_decrypt(str_repeat('a', 256), $result, $handle));
}

function test_forged_handles_legacy_runtime_format() {
    // legacy runtime handles look like ";;<index>" for public keys and "::<index>" for private ones
    check_forged_handle(';;999999');
    check_forged_handle('::999999');
    check_forged_handle(';;abc');
    check_forged_handle(';;');
    check_forged_handle('::');
}

function test_forged_handles_new_runtime_format() {
    // K2 runtime handles are a kind byte ('P' or 'S') followed by an 8-byte descriptor
    check_forged_handle('P' . str_repeat("\xff", 8));
    check_forged_handle('S' . str_repeat("\xff", 8));
    check_forged_handle('P' . str_repeat("\0", 8));
    check_forged_handle('S' . str_repeat("\0", 8));
    check_forged_handle('P12345678');
    check_forged_handle('S12345678');
    check_forged_handle('P');
    check_forged_handle('S');
    check_forged_handle('P' . str_repeat("\xff", 7));
    check_forged_handle('P' . str_repeat("\xff", 9));
}

