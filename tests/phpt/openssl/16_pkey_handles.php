    var_dump(openssl_pkey_get_private($encrypted_private_key_pem, 'secret123 ') === false);

    // passphrase is ignored for an unencrypted key
    var_dump(openssl_pkey_get_private($private_key_pem1, 'ignored') !== false);

    // passphrase is ignored when a handle is passed
    var_dump(openssl_pkey_get_private($handle, 'ignored') === $handle);
}

